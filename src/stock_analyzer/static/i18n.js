let LANG = "en";
try {
  // Remembered only to avoid a flash of English on load; the server setting decides.
  const cached = localStorage.getItem("language");
  if (cached && I18N[cached]) LANG = cached;
} catch { /* storage blocked */ }

function t(key, params) {
  const text = I18N[LANG][key] ?? I18N.en[key] ?? key;
  return params ? text.replace(/\{(\w+)\}/g, (m, name) => params[name] ?? m) : text;
}

// A fixed value from the server ("bullish", "buy", "pending"…) in the dashboard language.
// Unknown values are shown as they are.
function term(group, value) {
  if (value == null || value === "") return "";
  const key = `${group}.${value}`;
  return I18N[LANG][key] ?? I18N.en[key] ?? String(value);
}

// Fills the static page: data-i18n (text), data-i18n-placeholder, data-i18n-title.
function applyStatic() {
  document.documentElement.lang = LOCALES[LANG];
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
}

function setLanguage(lang) {
  if (!I18N[lang] || lang === LANG) return false;
  LANG = lang;
  try { localStorage.setItem("language", lang); } catch { /* storage blocked */ }
  applyStatic();
  return true;
}

